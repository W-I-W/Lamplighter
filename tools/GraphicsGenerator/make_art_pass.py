def ore(name, shape, pal, over=None, extra=None, rim=False):
    """rim — обвести контуром кристаллы, торчащие из камня (иначе их кончики выглядят срезанными); over при этом опускается на строку, чтобы контуру хватило места сверху."""
    if rim: over = ['.' * 16] + over[:-1]
    rows = overlay(shape, over) if over else shape
    if rim:
        g = [list(r) for r in rows]
        for y in range(16):
            for x in range(16):
                if rows[y][x] != '.': continue
                if any(0 <= x + dx < 16 and 0 <= y + dy < 16 and rows[y + dy][x + dx] in 'abcd' for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))): g[y][x] = 'o'
        rows = [''.join(r) for r in g]
    p = dict(pal); p.update(extra or {})
    return art(name, rows, p)



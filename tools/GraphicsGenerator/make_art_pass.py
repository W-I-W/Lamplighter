# ───────────────────────── стены: бесшовная каменная кладка ─────────────────────────
def wall(seed, pal, cells=7):
    """Бесшовный тайл стены: неровные камни (ячейки Вороного на торе), тёмные швы, светлая кромка сверху-слева, тень снизу-справа."""
    rnd = random.Random(seed)
    pts = [(rnd.uniform(0, 16), rnd.uniform(0, 16), rnd.random()) for _ in range(cells)]

    def owner(x, y):
        best, bi = 1e9, 0
        for i, (px, py, _) in enumerate(pts):
            dx = min(abs(x - px), 16 - abs(x - px)); dy = min(abs(y - py), 16 - abs(y - py))
            d = dx * dx + dy * dy * 1.6
            if d < best: best, bi = d, i
        return bi

    own = [[owner(x + .5, y + .5) for x in range(16)] for y in range(16)]
    seam = [[own[y][x] != own[y][(x + 1) % 16] or own[y][x] != own[(y + 1) % 16][x] for x in range(16)] for y in range(16)]
    im = Image.new('RGBA', (16, 16)); px = im.load()
    for y in range(16):
        for x in range(16):
            if seam[y][x]: c = pal['o']
            else:
                lit = seam[y][(x - 1) % 16] or seam[(y - 1) % 16][x]                     # кромка под швом слева/сверху
                shade = seam[y][(x + 1) % 16] or seam[(y + 1) % 16][x]
                tone = pts[own[y][x]][2]
                c = pal['1'] if lit and not shade else pal['3'] if shade and not lit else (pal['2'] if tone > .45 else pal['2b'])
                if not lit and not shade and rnd.random() < .07: c = pal['3']            # редкие выбоины
            px[x, y] = rgba(c)
    return im



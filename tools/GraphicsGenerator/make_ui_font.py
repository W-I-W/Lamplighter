def low(ch, rows, desc=None, top=2):               # x-height rows start at `top`
    G[ch] = ([''] * top + rows if top else rows, 0)
    if desc: G[ch] = (G[ch][0] + desc, 0)
def full(ch, rows, desc=None):
    G[ch] = (rows + (desc or []), 0)

